import { Fragment, useState } from "react";
import { Link } from "react-router-dom";
import { api, Json } from "../api";
import { Badge, fmtTime, Loading, Meter, pct, useApi, useToast } from "../components/ui";

export default function Governance() {
  const pol = useApi<Json>("/policies");
  const props = useApi<Json[]>("/policy-proposals");
  const [analysis, setAnalysis] = useState<Json | null>(null);
  const [comment, setComment] = useState("");
  const [tab, setTab] = useState("proposals");
  const { show, bump } = useToast();

  const decide = async (pid: string, decision: string) => {
    try {
      await api.post(`/policy-proposals/${pid}/decision`, { decision, comment });
      show(decision === "APPROVE" ? "Approved: new policy version created" : "Proposal rejected");
      setComment("");
      props.reload();
      pol.reload();
      bump();
    } catch (e) {
      show(String((e as Error).message), true);
    }
  };
  const analyze = async () => {
    try {
      const r = await api.post("/feedback/analyze");
      setAnalysis(r);
      props.reload();
      bump();
    } catch (e) {
      show(String((e as Error).message), true);
    }
  };

  if (!pol.data) return <Loading error={pol.error} />;
  const p = pol.data.active.policy;

  return (
    <div>
      <div className="page-head">
        <div><h1>Policies and feedback engine</h1><p>Stage 11: postmortem learnings become <b>proposed</b> policy changes. Nothing is applied without authorized human approval, and every change is versioned.</p></div>
        <div className="row"><span className="badge b-primary">Active policy v{p.version}</span><button className="btn" onClick={analyze}>Run feedback analysis</button></div>
      </div>
      {analysis && (
        <div className="card" style={{ marginBottom: 16 }}>
          <h2>Feedback analysis (policy v{analysis.policy_version})</h2>
          <table><thead><tr><th>Change category</th><th className="num">Incidents</th><th className="num">Threshold</th><th>Outcome</th><th>Policy path</th></tr></thead>
            <tbody>{analysis.observations.map((o: Json) => <tr key={o.category}><td>{o.category}</td><td className="num">{o.count}</td><td className="num">{o.threshold}</td>
              <td><Badge v={o.status.toUpperCase()} tone={o.status === "proposal_created" ? "warn" : "neutral"} /></td><td className="mono small">{o.path || "—"}</td></tr>)}</tbody></table>
        </div>
      )}
      <div className="tabs">{["proposals", "active policy", "version history"].map((t) => <button key={t} className={tab === t ? "active" : ""} onClick={() => setTab(t)}>{t}</button>)}</div>

      {tab === "proposals" && (
        <div className="stack">
          {!props.data ? <Loading /> : props.data.length === 0 ? <div className="empty">No proposals. They appear when repeated incidents share a change category.</div> :
            props.data.map((pr) => (
              <div key={pr.id} className="card">
                <div className="row"><h2 style={{ margin: 0 }}>{pr.id}: {pr.title}</h2><Badge v={pr.status} /><span className="right small muted">based on v{pr.base_version} · {fmtTime(pr.created_at)}</span></div>
                <p>{pr.data.rationale}</p>
                <dl className="kv">
                  <dt>Policy path</dt><dd className="mono">{pr.data.path}</dd>
                  <dt>Change</dt><dd><b>{pr.data.current_value}</b> → <b>{pr.data.proposed_value}</b> points</dd>
                  <dt>Generated by</dt><dd>{pr.data.generated_by} (auto-applied: {String(pr.data.auto_applied)})</dd>
                  {pr.decided_by && <><dt>Decision</dt><dd>{pr.status} by {pr.decided_by} at {fmtTime(pr.decided_at)} {pr.decision_comment && `: "${pr.decision_comment}"`}
                    {pr.data.resulting_version && <> → policy v{pr.data.resulting_version}</>}</dd></>}
                </dl>
                <h3 style={{ marginTop: 12 }}>Supporting evidence</h3>
                <div className="table-wrap"><table><thead><tr><th>Incident</th><th>Postmortem</th><th>Service</th><th>Severity</th><th>Root cause</th></tr></thead>
                  <tbody>{pr.data.evidence.map((e: Json) => <tr key={e.postmortem_id}><td><Link to={`/incidents/${e.incident_id}`}>{e.incident_id}</Link></td><td>{e.postmortem_id}</td>
                    <td>{e.service}</td><td><Badge v={e.severity} /></td><td className="small">{e.root_cause}</td></tr>)}</tbody></table></div>
                {pr.status === "PENDING" && (
                  <div className="row" style={{ marginTop: 12 }}>
                    <input style={{ flex: 1, minWidth: 200 }} placeholder="Decision comment" value={comment} onChange={(e) => setComment(e.target.value)} />
                    <button className="btn btn-ok" onClick={() => decide(pr.id, "APPROVE")}>Approve and version</button>
                    <button className="btn btn-bad" onClick={() => decide(pr.id, "REJECT")}>Reject</button>
                    <span className="small muted">Requires governance_admin</span>
                  </div>
                )}
              </div>
            ))}
        </div>
      )}

      {tab === "active policy" && (
        <div className="grid g2">
          <div className="card">
            <h2>Risk dimension weights</h2>
            {Object.entries(p.risk.weights).map(([k, v]) => <Meter key={k} label={k.replace(/_/g, " ")} value={(v as number) * 100} right={pct(v as number)} />)}
            <h3 style={{ marginTop: 14 }}>Risk bands</h3>
            <table><thead><tr><th>Level</th><th>Range</th><th>Decision</th><th>Required approvals</th></tr></thead>
              <tbody>{p.risk.levels.map((l: Json) => <tr key={l.name}><td><Badge v={l.name} /></td><td>{l.min}–{l.max}</td>
                <td><Badge v={p.risk.level_requirements[l.name].decision} /></td><td className="small">{p.risk.level_requirements[l.name].required_approvals.join(", ") || "none"}</td></tr>)}</tbody></table>
          </div>
          <div className="card">
            <h2>Development quality objective</h2>
            <div className="small muted">Threshold {pct(p.quality.development.threshold)}</div>
            {Object.entries(p.quality.development.objective).map(([k, v]: [string, Json]) => <Meter key={k} label={k.replace(/_/g, " ")} value={v.weight * 100} right={pct(v.weight)} />)}
            <h3 style={{ marginTop: 14 }}>Loop limits</h3>
            <dl className="kv">{Object.entries(p.loop).map(([k, v]) => <Fragment key={k}><dt>{k.replace(/_/g, " ")}</dt><dd>{String(v)}</dd></Fragment>)}</dl>
          </div>
          <div className="card">
            <h2>Health thresholds</h2>
            <table><tbody>{Object.entries(p.health.thresholds).map(([k, t]: [string, Json]) => <tr key={k}><td>{t.label}</td><td className="num">{t.max !== undefined ? `≤ ${t.max}` : `≥ ${t.min}`}{t.unit}</td></tr>)}</tbody></table>
            <div className="small" style={{ marginTop: 8 }}>Rollout steps: {p.health.rollout_steps.join("% → ")}% · breach action {p.health.breach_action}</div>
          </div>
          <div className="card">
            <h2>Risk factor points</h2>
            <pre className="json">{JSON.stringify(p.risk.factors, null, 2)}</pre>
          </div>
        </div>
      )}

      {tab === "version history" && (
        <div className="card">
          <table><thead><tr><th>Version</th><th>Active</th><th>Created by</th><th>Summary</th><th>Changes</th><th>Proposal</th><th>Created</th></tr></thead>
            <tbody>{pol.data.versions.map((v: Json) => (
              <tr key={v.version}><td><b>v{v.version}</b></td><td>{v.active ? <Badge v="ACTIVE" tone="ok" /> : ""}</td><td>{v.created_by}</td><td>{v.change_summary}</td>
                <td className="small mono">{v.changes.map((c: Json) => `${c.path}: ${c.old_value} → ${c.new_value}`).join("; ") || "—"}</td><td>{v.proposal_id || "—"}</td><td className="small">{fmtTime(v.created_at)}</td></tr>))}</tbody></table>
        </div>
      )}
    </div>
  );
}
